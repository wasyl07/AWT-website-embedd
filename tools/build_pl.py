#!/usr/bin/env python3
"""Generate pl/index.html from index.html + i18n/pl.json.

index.html is the single source (English). Run this after changing either file:

    python3 tools/build_pl.py

Google only indexes text that is in the HTML, so the Polish version needs its
own page instead of being swapped in by JavaScript.
"""
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = "https://www.awt-embedded.com"

HEAD_PL = {
    "title": "Projektowanie elektroniki i systemów wbudowanych — AWT, Polska",
    "description": "Projektowanie elektroniki i oprogramowania systemów wbudowanych, prototypy, "
                   "testy i produkcja małoseryjna oraz zdalne aktualizacje i monitoring. "
                   "Jeden partner od pomysłu do gotowego produktu.",
    "og_title": "Projektowanie elektroniki i systemów wbudowanych — AWT",
    "og_description": "Projekt, prototyp, testy, produkcja i utrzymanie urządzeń "
                      "elektronicznych — jeden wykonawca od koncepcji do gotowego produktu.",
}


def main() -> int:
    src = (ROOT / "index.html").read_text(encoding="utf-8")
    pl = json.loads((ROOT / "i18n" / "pl.json").read_text(encoding="utf-8"))
    s = src

    def sub(pattern, repl, count=1, flags=0):
        nonlocal s
        s, n = re.subn(pattern, repl, s, count=count, flags=flags)
        if n == 0:
            sys.exit(f"build_pl: pattern not found: {pattern}")

    esc = lambda t: html.escape(t, quote=True)

    sub(r'<html lang="en">', '<html lang="pl">')
    sub(r"<title>.*?</title>", f"<title>{esc(HEAD_PL['title'])}</title>")
    sub(r'<meta name="description" content="[^"]*">',
        f'<meta name="description" content="{esc(HEAD_PL["description"])}">')
    sub(r'<link rel="canonical" href="[^"]*">', f'<link rel="canonical" href="{SITE}/pl/">')
    sub(r'<meta property="og:title" content="[^"]*">',
        f'<meta property="og:title" content="{esc(HEAD_PL["og_title"])}">')
    sub(r'<meta property="og:description" content="[^"]*">',
        f'<meta property="og:description" content="{esc(HEAD_PL["og_description"])}">')
    sub(r'<meta property="og:url" content="[^"]*">', f'<meta property="og:url" content="{SITE}/pl/">')
    sub(r'<meta property="og:locale" content="en_GB">\n  <meta property="og:locale:alternate" content="pl_PL">',
        '<meta property="og:locale" content="pl_PL">\n  <meta property="og:locale:alternate" content="en_GB">')
    # The EN page redirects Polish visitors here; the PL page must not redirect.
    sub(r'  <script id="lang-redirect">.*?</script>\n', "", flags=re.S)

    # Language links: swap targets and the current marker.
    sub(r'<a href="\./" data-lang="en" hreflang="en" lang="en" aria-current="page">EN</a>',
        '<a href="../" data-lang="en" hreflang="en" lang="en">EN</a>')
    sub(r'<a href="pl/" data-lang="pl" hreflang="pl" lang="pl">PL</a>',
        '<a href="./" data-lang="pl" hreflang="pl" lang="pl" aria-current="page">PL</a>')

    # Relative asset/page paths now live one level up.
    s = re.sub(r'\b(href|src)="(?!#|https?:|mailto:|tel:|/|\.\./|\./)([^"]+)"', r'\1="../\2"', s)

    # Service links point to the Polish service pages (see tools/build_services.py).
    services = json.loads((ROOT / "content" / "services.json").read_text(encoding="utf-8"))["services"]
    for svc in services:
        sub(rf'href="\.\./services/{svc["slug"]["en"]}/"', f'href="uslugi/{svc["slug"]["pl"]}/"', count=0)

    # Translate every data-i18n element (text-only content).
    seen = set()

    def tr(m):
        key = m.group(3)
        if key not in pl:
            sys.exit(f"build_pl: missing Polish text for '{key}' in i18n/pl.json")
        seen.add(key)
        return m.group(1) + html.escape(pl[key], quote=False) + m.group(4)

    s = re.sub(r'(<(\w+)\b[^>]*\sdata-i18n="([^"]+)"[^>]*>)[^<]*(</\2>)', tr, s)
    left = set(re.findall(r'data-i18n="([^"]+)"', s)) - seen
    if left:
        sys.exit(f"build_pl: could not translate (element has child tags?): {sorted(left)}")

    banner = "<!-- Generated by tools/build_pl.py from index.html + i18n/pl.json. Do not edit. -->\n"
    out = ROOT / "pl" / "index.html"
    out.parent.mkdir(exist_ok=True)
    out.write_text(s.replace("<!doctype html>\n", "<!doctype html>\n" + banner, 1), encoding="utf-8")
    unused = set(pl) - seen
    print(f"wrote {out.relative_to(ROOT)} ({len(seen)} strings)"
          + (f"; unused keys in pl.json: {sorted(unused)}" if unused else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
