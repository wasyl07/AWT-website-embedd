// AWT website — theme toggle, language preference and contact form.
(() => {
  const EMAIL = "adam@awt-embedded.com";

  const MSG = {
    en: { missing: "Please provide your name and a valid email address.",
          opened: "Your email app should open with the message ready. If it doesn't, write to " + EMAIL + ".",
          dark: "Switch to dark mode", light: "Switch to light mode",
          prev: "Previous month", next: "Next month", chosen: "Selected:" },
    pl: { missing: "Prosimy podać imię i nazwisko oraz poprawny adres e-mail.",
          opened: "Program pocztowy powinien otworzyć się z gotową wiadomością. Jeśli tak się nie stało, prosimy o kontakt: " + EMAIL + ".",
          dark: "Włącz tryb ciemny", light: "Włącz tryb jasny",
          prev: "Poprzedni miesiąc", next: "Następny miesiąc", chosen: "Wybrany termin:" },
  };

  // Each language has its own page (/ and /pl/), generated by tools/build_pl.py.
  const lang = document.documentElement.lang === "pl" ? "pl" : "en";
  document.querySelectorAll("[data-lang]").forEach((a) =>
    a.addEventListener("click", () => { try { localStorage.setItem("awt-lang", a.dataset.lang); } catch {} }));

  const note = document.getElementById("form-note");

  // Theme: light / dark. Light by default (set inline in <head>); dark only if the visitor picks it.
  const root = document.documentElement;
  const themeBtn = document.getElementById("theme-toggle");
  function updateThemeLabel() {
    const dark = root.dataset.theme === "dark";
    themeBtn.setAttribute("aria-label", dark ? MSG[lang].light : MSG[lang].dark);
    themeBtn.title = themeBtn.getAttribute("aria-label");
  }
  themeBtn.addEventListener("click", () => {
    root.dataset.theme = root.dataset.theme === "dark" ? "light" : "dark";
    try { localStorage.setItem("awt-theme", root.dataset.theme); } catch {}
    updateThemeLabel();
  });
  updateThemeLabel();

  document.getElementById("year").textContent = new Date().getFullYear();

  // Contact form → opens the visitor's mail client with a prefilled message.
  const form = document.getElementById("contact-form");
  if (!form) return; // service pages have no form

  // Preferred call time, added to the message. Empty when nothing is selected.
  let preferredCall = "";

  // Calendar of free times from data/slots.json (see tools/sync_calendar.py). It stays hidden
  // if the file is missing or out of date, so visitors are never shown stale availability.
  const MAX_AGE_DAYS = 3;
  function showSlotPicker(data) {
    const picker = document.getElementById("slot-picker");
    const now = Date.now();
    const age = (now - Date.parse(data.generated + "T00:00:00Z")) / 86400000;
    if (!picker || !(age <= MAX_AGE_DAYS)) return;

    const earliest = now + data.notice_hours * 3600000;
    const dayKey = (d) => `${d.getFullYear()}-${d.getMonth()}-${d.getDate()}`;
    const days = new Map(); // visitor's local day → free times that day
    const slots = data.slots.map((s) => new Date(s)).filter((d) => d.getTime() >= earliest);
    if (!slots.length) return;
    slots.forEach((d) => {
      if (!days.has(dayKey(d))) days.set(dayKey(d), []);
      days.get(dayKey(d)).push(d);
    });

    const locale = lang === "pl" ? "pl" : "en-GB";
    const fmt = (options) => new Intl.DateTimeFormat(locale, options);
    const zone = Intl.DateTimeFormat().resolvedOptions().timeZone;
    const grid = document.getElementById("cal-grid");
    const times = document.getElementById("cal-times");
    const month = document.getElementById("cal-month");
    const chosen = document.getElementById("cal-chosen");
    const prev = document.getElementById("cal-prev");
    const next = document.getElementById("cal-next");
    prev.setAttribute("aria-label", MSG[lang].prev);
    next.setAttribute("aria-label", MSG[lang].next);

    const monthIndex = (d) => d.getFullYear() * 12 + d.getMonth();
    const firstMonth = monthIndex(slots[0]);
    const lastMonth = monthIndex(slots[slots.length - 1]);
    let shownMonth = firstMonth;
    let selectedDay = null;
    let selectedSlot = null;

    function select(slot) {
      selectedSlot = selectedSlot && selectedSlot.getTime() === slot.getTime() ? null : slot;
      times.querySelectorAll("button").forEach((b) =>
        b.setAttribute("aria-pressed", String(!!selectedSlot && b.dataset.slot === selectedSlot.toISOString())));
      if (!selectedSlot) { preferredCall = ""; chosen.textContent = ""; return; }

      const date = { weekday: "short", day: "numeric", month: "short", year: "numeric", hour: "2-digit", minute: "2-digit", hour12: false };
      const inZone = (timeZone) => new Intl.DateTimeFormat("en-GB", { ...date, timeZone }).format(selectedSlot);
      preferredCall = `${inZone(data.timezone)} ${data.timezone}, ${data.minutes} min`
        + (zone && zone !== data.timezone ? ` (visitor's time: ${inZone(zone)} ${zone})` : "");
      chosen.textContent = `${MSG[lang].chosen} ${fmt({ weekday: "long", day: "numeric", month: "long", hour: "2-digit", minute: "2-digit", hour12: false }).format(selectedSlot)}`
        + (zone ? ` (${zone})` : "");
    }

    function showTimes(key) {
      selectedDay = key;
      grid.querySelectorAll("[data-day]").forEach((b) => b.setAttribute("aria-pressed", String(b.dataset.day === key)));
      times.replaceChildren(...days.get(key).map((slot) => {
        const b = document.createElement("button");
        b.type = "button";
        b.className = "cal__time";
        b.dataset.slot = slot.toISOString();
        b.textContent = fmt({ hour: "2-digit", minute: "2-digit", hour12: false }).format(slot);
        b.setAttribute("aria-pressed", String(!!selectedSlot && slot.getTime() === selectedSlot.getTime()));
        b.addEventListener("click", () => select(slot));
        return b;
      }));
    }

    function showMonth() {
      const first = new Date(Math.floor(shownMonth / 12), shownMonth % 12, 1);
      month.textContent = fmt({ month: "long", year: "numeric" }).format(first);
      prev.disabled = shownMonth === firstMonth;
      next.disabled = shownMonth === lastMonth;

      const cells = [];
      for (let i = 0; i < 7; i++) { // Monday first; 2 Nov 2026 is a Monday
        const head = document.createElement("span");
        head.className = "cal__weekday";
        head.textContent = fmt({ weekday: "short" }).format(new Date(2026, 10, 2 + i));
        cells.push(head);
      }
      for (let i = 0; i < (first.getDay() + 6) % 7; i++) cells.push(document.createElement("span"));
      const count = new Date(first.getFullYear(), first.getMonth() + 1, 0).getDate();
      for (let n = 1; n <= count; n++) {
        const day = new Date(first.getFullYear(), first.getMonth(), n);
        const key = dayKey(day);
        const b = document.createElement("button");
        b.type = "button";
        b.className = "cal__day";
        b.textContent = n;
        b.setAttribute("aria-label", fmt({ weekday: "long", day: "numeric", month: "long" }).format(day));
        if (days.has(key)) {
          b.dataset.day = key;
          b.setAttribute("aria-pressed", String(key === selectedDay));
          b.addEventListener("click", () => showTimes(key));
        } else {
          b.disabled = true;
        }
        cells.push(b);
      }
      grid.replaceChildren(...cells);
    }

    prev.addEventListener("click", () => { shownMonth--; showMonth(); });
    next.addEventListener("click", () => { shownMonth++; showMonth(); });
    showMonth();
    picker.hidden = false;
  }
  fetch("/data/slots.json")
    .then((r) => (r.ok ? r.json() : null))
    .then((data) => { if (data) showSlotPicker(data); })
    .catch(() => {});

  form.addEventListener("submit", (e) => {
    e.preventDefault();
    const fd = new FormData(form);
    const name = (fd.get("name") || "").toString().trim();
    const email = (fd.get("email") || "").toString().trim();
    const company = (fd.get("company") || "").toString().trim();
    const needs = fd.getAll("need").join(", ");

    const checks = [
      ["f-name", name.length > 0],
      ["f-email", /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)],
    ];
    let ok = true;
    checks.forEach(([id, valid]) => {
      document.getElementById(id).closest(".field").classList.toggle("invalid", !valid);
      if (!valid) ok = false;
    });
    if (!ok) { note.textContent = MSG[lang].missing; return; }

    const subject = `Quote request — ${company || name}${needs ? " (" + needs + ")" : ""}`;
    const body = `Name: ${name}\nCompany: ${company || "-"}\nEmail: ${email}\nServices: ${needs || "-"}\n${preferredCall ? `Preferred call: ${preferredCall}\n` : ""}\n`;
    window.location.href = `mailto:${EMAIL}?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
    note.textContent = MSG[lang].opened;
  });
})();
